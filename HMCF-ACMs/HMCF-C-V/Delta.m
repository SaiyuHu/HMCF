function Delta_h = Delta(phi, epsilon)
%==========================================================================
% Delta —— 正则化（光滑）Dirac 函数 δε(φ)
%--------------------------------------------------------------------------
% 功能：
%   作为 Heaviside 函数 Hε(φ) 的导数，δε(φ) = dHε/dφ，用于将演化方程
%   的作用范围限制在零水平集附近的窄带内。
%
% 数学表达式：
%           δε(φ) = (ε/π) / (ε^2 + φ^2)
%   当 ε→0 时 δε(φ) 收敛于 Dirac δ 函数。
%
% 输入：
%   phi     : 水平集函数
%   epsilon : 正则化参数，控制窄带宽度
%
% 输出：
%   Delta_h : 与 phi 同尺寸的正则化 Dirac 函数值（非负）
%
%==========================================================================
Delta_h = (epsilon/pi)./(epsilon^2+ phi.^2);