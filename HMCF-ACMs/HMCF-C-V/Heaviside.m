function H = Heaviside(phi,epsilon)
%==========================================================================
% Heaviside —— 正则化（光滑）Heaviside 函数 Hε(φ)
%--------------------------------------------------------------------------
% 功能：
%   以 arctan 型光滑函数逼近阶跃函数，用于在 C-V 泛函中区分演化区域
%   的内部（Hε≈1）与外部（Hε≈0），并保证泛函可微。
%
% 数学表达式：
%           Hε(φ) = 1/2 · [ 1 + (2/π)·arctan(φ/ε) ]
%   当 ε→0 时 Hε(φ) 收敛于标准 Heaviside 函数。
%
% 输入：
%   phi     : 水平集函数
%   epsilon : 正则化参数，控制过渡带宽度
%
% 输出：
%   H       : 与 phi 同尺寸的正则化 Heaviside 函数值，取值范围 (0,1)
%
%   Original code: Chunming Li, 04/26/2004.
%==========================================================================
H = 0.5*(1+ (2/pi)*atan(phi./epsilon));