function [C1,C2] = binaryfit(phi,U,epsilon)
%==========================================================================
% binaryfit —— 计算 C-V 能量泛函的区域最优灰度拟合常数 C1、C2
%--------------------------------------------------------------------------
% 功能：
%   在给定水平集函数 phi 下，分别对零水平集内部（φ>0）与外部（φ<0）
%   的区域计算使拟合误差最小的灰度常数（即加权灰度均值）。
%
% 数学背景：
%   引入正则化 Heaviside 函数 Hε(φ)，则最优拟合常数由下式给出
%           C1 = ∫Ω U·Hε(φ) dx / ∫Ω Hε(φ) dx      （区域 φ>0）
%           C2 = ∫Ω U·(1-Hε(φ)) dx / ∫Ω (1-Hε(φ)) dx （区域 φ<0）
%   离散实现即为对 Hε(φ)·U 与 Hε(φ) 分别求和后作比。
%
% 输入：
%   phi     : 水平集函数，尺寸 [nrow, ncol]
%   U       : 灰度图像矩阵，尺寸 [nrow, ncol]
%   epsilon : Heaviside 函数正则化参数
%
% 输出：
%   C1      : 区域 φ>0 内的最优灰度拟合常数
%   C2      : 区域 φ<0 内的最优灰度拟合常数
%
%   Original code: Chunming Li, 04/26/2004.
%==========================================================================

% 计算正则化 Heaviside 函数 Hε(φ)
H = Heaviside(phi,epsilon);

% 区域 φ>0：C1 = Σ(H·U) / Σ(H)
a = H.*U;
numer_1 = sum(a(:));
denom_1 = sum(H(:));
C1 = numer_1/denom_1;

% 区域 φ<0：C2 = Σ((1-H)·U) / Σ(1-H)
b = (1-H).*U;
numer_2 = sum(b(:));
c = 1-H;
denom_2 = sum(c(:));
C2 = numer_2/denom_2;