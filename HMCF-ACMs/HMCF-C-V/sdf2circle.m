function f = sdf2circle(nrow,ncol,ic,jc,r)
%==========================================================================
% sdf2circle —— 构造圆形的符号距离函数 (Signed Distance Function, SDF)
%--------------------------------------------------------------------------
% 功能：
%   生成一个网格上的函数场，其取值等于各网格点到圆心 (ic, jc)、半径 r
%   的圆的距离，并带符号：圆外为正、圆内为负，因而其零水平集恰为该圆。
%   常作为水平集演化算法的初始轮廓。
%
% 数学表达式：
%           f(X,Y) = sqrt( (X - jc)^2 + (Y - ic)^2 ) - r
%   其中 (X,Y) 为网格点坐标，(ic, jc) 为圆心位置，r 为半径。
%
% 输入：
%   nrow : 图像行数（Y 方向尺寸）
%   ncol : 图像列数（X 方向尺寸）
%   ic   : 圆心所在行坐标
%   jc   : 圆心所在列坐标
%   r    : 圆半径（像素）
%
% 输出：
%   f    : 尺寸为 [nrow, ncol] 的圆形符号距离函数
%
% 注：若在初始化水平集时取其负值（phi = -f），则圆内为 φ>0、
%     圆外为 φ<0，与 EVOLUTION_* 中"φ>0 为前景"的约定一致。
%
%   Original code: Chunming Li, 04/26/2004.
%==========================================================================

% 构造网格坐标（X 为列坐标、Y 为行坐标）
[X,Y] = meshgrid(1:ncol, 1:nrow);

% 到圆心的欧氏距离减去半径，得到符号距离场
f = sqrt((X-jc).^2+(Y-ic).^2)-r;

%f=sdf2circle(100,50,51,25,10);figure;imagesc(f)