function phi = EVOLUTION_CV(I, phi, delta_t, epsilon, mu, pu)
%==========================================================================
% EVOLUTION_CV —— 经典 C-V 模型的显式欧拉水平集单步演化（对照组）
%--------------------------------------------------------------------------
% 功能：
%   在 C-V 能量泛函梯度流框架下，采用显式一阶欧拉时间离散、一阶
%   中心差分空间离散，将水平集函数 phi 推进一个时间步。该函数作为
%   本文 HMCF 格式的对比基准（baseline）。
%
% 数学背景：
%   连续演化方程
%       ∂φ/∂t = δε(φ)·[ μ·κ + (-(I - C1)^2 + (I - C2)^2) + ν·P(φ) ]
%   其中
%       δε(φ)   —— 正则化 Dirac 函数；
%       μ·κ     —— 长度项（κ 为零水平集曲率）；
%       (I-C1)^2、(I-C2)^2 —— 区域数据拟合项，C1、C2 为内外最优灰度均值；
%       ν·P(φ)  —— 距离正则化惩罚项 P(φ) = 4·Δφ + κ，权重 ν = pu。
%
% 输入：
%   I       : double 型灰度图像矩阵，尺寸 [nrow, ncol]
%   phi     : 当前水平集函数，尺寸 [nrow, ncol]
%   delta_t : 时间步长
%   epsilon : Heaviside / Dirac 函数的正则化参数
%   mu      : 长度项权重
%   pu      : 距离正则化（惩罚）项权重
%
% 输出：
%   phi     : 演化一步后的水平集函数（已施加诺伊曼边界条件）
%
%==========================================================================

% 步骤 1：计算正则化 Dirac 函数 δε(φ)
delta_h = Delta(phi, epsilon);

% 步骤 2：计算曲率 κ，并分别组装长度项、惩罚项与数据项
K = -curvature(phi);
PenaltyTerm = pu * (4 * del2(phi) + K);      % 距离正则化惩罚项（4*del2≈Δφ）
LengthTerm = mu * K;                          % 长度正则化项
[C1, C2] = binaryfit(phi, I, epsilon);        % 区域内外最优灰度拟合常数
ImageTerm = (-(I - C1).^2 + (I - C2).^2);     % 数据拟合项

% 步骤 3：组装演化速度场并显式欧拉推进一个时间步
phi_t = delta_h .* (LengthTerm + ImageTerm + PenaltyTerm);
phi = phi + delta_t * phi_t;

% 步骤 4：施加诺伊曼（自由）边界条件
phi = BoundNeumann_bc(phi);
end

function phi = BoundNeumann_bc(phi)
%--------------------------------------------------------------------------
% BoundNeumann_bc —— 诺伊曼（自由）边界条件的虚拟网格点实现
%   通过令边界点的值等于其相邻内点的值（∂φ/∂n = 0 的一阶离散），
%   保证边界处零通量。
%--------------------------------------------------------------------------
    % 四条边界：镜像内侧相邻点
    phi(1, :)   = phi(2, :);        % 上边界
    phi(end, :) = phi(end-1, :);    % 下边界
    phi(:, 1)   = phi(:, 2);        % 左边界
    phi(:, end) = phi(:, end-1);    % 右边界

    % 四个角点：取两个相邻边界点的平均值
    phi(1, 1)       = (phi(1, 2) + phi(2, 1)) / 2;
    phi(1, end)     = (phi(1, end-1) + phi(2, end)) / 2;
    phi(end, 1)     = (phi(end-1, 1) + phi(end, 2)) / 2;
    phi(end, end)   = (phi(end-1, end) + phi(end, end-1)) / 2;
end