function [bdy,bdx] = backward_gradient(f)
%==========================================================================
% backward_gradient —— 向后差分梯度算子
%--------------------------------------------------------------------------
% 功能：
%   以一阶向后差分估计标量场的两个方向偏导（用于曲率计算的梯度估计）。
%
% 数学表达式（网格步长取 1）：
%           bdx(i,j) = f(i,j) - f(i-1,j)      （沿行方向的偏导 ∂f/∂x）
%           bdy(i,j) = f(i,j) - f(i,j-1)      （沿列方向的偏导 ∂f/∂y）
%   第一行 / 第一列无向后邻点，置零。
%
% 输入：
%   f   : 标量场矩阵，尺寸 [nr, nc]
%
% 输出：
%   bdy : 列方向偏导 ∂f/∂y
%   bdx : 行方向偏导 ∂f/∂x
%
% 注：函数返回顺序为 [bdy, bdx]，与原实现保持一致。
%   Original code: Chunming Li, 04/26/2004.
%==========================================================================
[nr,nc] = size(f);
bdx = zeros(nr,nc);
bdy = zeros(nr,nc);

% 行方向向后差分（结果存放于第 2..nr 行）
bdx(2:nr,:) = f(2:nr,:) - f(1:nr-1,:);

% 列方向向后差分（结果存放于第 2..nc 列）
bdy(:,2:nc) = f(:,2:nc) - f(:,1:nc-1);