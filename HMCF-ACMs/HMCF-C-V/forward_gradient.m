function [fdy,fdx] = forward_gradient(f)
%==========================================================================
% forward_gradient —— 向前差分梯度算子
%--------------------------------------------------------------------------
% 功能：
%   以一阶向前差分估计标量场的两个方向偏导（用于曲率计算的梯度估计）。
%
% 数学表达式（网格步长取 1）：
%           fdx(i,j) = f(i+1,j) - f(i,j)      （沿行方向的偏导 ∂f/∂x）
%           fdy(i,j) = f(i,j+1) - f(i,j)      （沿列方向的偏导 ∂f/∂y）
%   最后一行 / 最后一列无向前邻点，置零。
%
% 输入：
%   f   : 标量场矩阵，尺寸 [nr, nc]
%
% 输出：
%   fdy : 列方向偏导 ∂f/∂y
%   fdx : 行方向偏导 ∂f/∂x
%
% 注：函数返回顺序为 [fdy, fdx]，与原实现保持一致。
%   Original code: Chunming Li, 04/26/2004.
%==========================================================================
[nr,nc] = size(f);
fdx = zeros(nr,nc);
fdy = zeros(nr,nc);

% 行方向向前差分（结果存放于前 nr-1 行）
a = f(2:nr,:) - f(1:nr-1,:);
fdx(1:nr-1,:) = a;

% 列方向向前差分（结果存放于前 nc-1 列）
b = f(:,2:nc) - f(:,1:nc-1);
fdy(:,1:nc-1) = b;