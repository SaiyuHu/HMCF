function phi = EVOLUTION_RK(Img, phi, delta_t, epsilon, b, pu)
%==========================================================================
% EVOLUTION_RK —— 基于 HMCF 高阶紧致差分格式的水平集单步演化
%--------------------------------------------------------------------------
% 功能：
%   构造 C-V 能量泛函梯度流的速度场 phi_t，并调用 HMCF 数值格式
%   （四阶龙格-库塔时间离散 + 四阶紧致空间离散，见
%   pde_RK4_Truncation4.m）将水平集函数 phi 向前推进一个时间步。
%
% 数学背景：
%   连续演化方程（C-V 梯度流）
%       ∂φ/∂t = δε(φ)·[ -(I - C1)^2 + (I - C2)^2 + ν·P(φ) ]
%   其中
%       δε(φ)                —— 正则化 Dirac 函数，控制演化仅发生在零水平集附近；
%       C1、C2               —— 区域内外最优灰度拟合常数（binaryfit 求得）；
%       P(φ) = 4·Δφ + κ      —— 距离正则化惩罚项，抑制 |∇φ| 偏离 1；
%       κ = -div(∇φ/|∇φ|)     —— 零水平集曲率。
%
% 输入：
%   Img     : double 型灰度图像矩阵（受噪图像），尺寸 [nrow, ncol]
%   phi     : 当前水平集函数（符号距离函数），尺寸 [nrow, ncol]
%   delta_t : 时间步长
%   epsilon : Heaviside / Dirac 函数的正则化参数
%   b       : 内部子步时间步长估计所用的扩散系数
%   pu      : 距离正则化（惩罚）项权重 ν
%
% 输出：
%   phi     : 演化一步后的水平集函数
%==========================================================================

% 步骤 1：计算演化区域内外的最优灰度拟合常数 C1（φ>0）与 C2（φ<0）
[C1, C2] = binaryfit(phi, Img, epsilon);

% 步骤 2：计算正则化 Dirac 函数 δε(φ)，作为演化方程前的系数
Delta_h = Delta(phi, epsilon);

% 步骤 3：计算曲率 κ = -div(∇φ/|∇φ|) 与距离正则化惩罚项 P(φ) = 4·Δφ + κ
%   注：MATLAB 内置 del2 为离散 Laplacian 的 1/4 缩放，故 4*del2(phi) ≈ Δφ
K = -curvature(phi);
PenaltyTerm = pu * (4 * del2(phi) + K);

% 步骤 4：组装演化速度场 phi_t = δε(φ)·[ -(I-C1)^2 + (I-C2)^2 + P(φ) ]
phi_t = Delta_h .* (-(Img - C1).^2 + (Img - C2).^2 + PenaltyTerm);

% 步骤 5：使用 HMCF 数值格式（RK4 时间离散 + 紧致空间离散）推进一个时间步
phi = pde_RK4_Truncation4(phi, delta_t, phi_t, b);